-- Schema reference for Console Connect.
-- Run in Supabase SQL Editor only if these tables do not already exist.

create table if not exists public.console_users (
  id bigint generated by default as identity primary key,
  user_id text not null unique,
  password text not null
);

create table if not exists public.high_scores (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.console_users(id) on delete cascade,
  game text not null,
  high_score integer not null default 0 check (high_score >= 0),
  updated_at timestamptz not null default now(),
  constraint high_scores_user_game_unique unique (user_id, game)
);

-- Keep direct client access disabled; the Edge Function uses the server-side
-- service-role key. Never expose that key in the ESP32 firmware or browser.
alter table public.console_users enable row level security;
alter table public.high_scores enable row level security;
